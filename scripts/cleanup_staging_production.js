const mongoose = require('mongoose');
require('dotenv').config({ path: '../.env' }); // to read MONGO_URI

// Models we need to clean up
const userSchema = new mongoose.Schema({}, { strict: false, collection: 'users' });
const User = mongoose.model('User', userSchema);
const dishSchema = new mongoose.Schema({ owner: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } }, { strict: false, collection: 'dishes' });
const Dish = mongoose.model('Dish', dishSchema);
const menuSchema = new mongoose.Schema({ owner: { type: mongoose.Schema.Types.ObjectId, ref: 'User' }, chef: { type: mongoose.Schema.Types.ObjectId, ref: 'User'} }, { strict: false, collection: 'menus' });
const Menu = mongoose.model('Menu', menuSchema);
const sectionSchema = new mongoose.Schema({ owner: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } }, { strict: false, collection: 'sections' });
const Section = mongoose.model('Section', sectionSchema);
const branchSchema = new mongoose.Schema({ chef: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } }, { strict: false, collection: 'chefbranches' });
const ChefBranch = mongoose.model('ChefBranch', branchSchema);
const reelSchema = new mongoose.Schema({ chef: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } }, { strict: false, collection: 'reels' });
const Reel = mongoose.model('Reel', reelSchema);
const orderSchema = new mongoose.Schema({ 
    chef: { type: mongoose.Schema.Types.ObjectId, ref: 'User' }, 
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } 
}, { strict: false, collection: 'orders' });
const Order = mongoose.model('Order', orderSchema);
const storySchema = new mongoose.Schema({ chef: { type: mongoose.Schema.Types.ObjectId, ref: 'User' } }, { strict: false, collection: 'stories' });
const Story = mongoose.model('Story', storySchema);
const notificationSchema = new mongoose.Schema({
    to_user: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    from_user: { type: mongoose.Schema.Types.ObjectId, ref: 'User' }
}, { strict: false, collection: 'notifications' });
const Notification = mongoose.model('Notification', notificationSchema);


const testEmails = [
  'mario@foodtok.com',
  'isabella@foodtok.com',
  'chen@foodtok.com',
  'ahmed@foodtok.com',
  'sophie@foodtok.com',
  'john@foodtok.com',
  'sarah@foodtok.com',
  'experimental_chef@feedyum.com',
  'experimental_user@feedyum.com'
];

async function cleanupStaging() {
  try {
    const mongoURI = process.env.MONGO_URI;
    if (!mongoURI) {
        console.error('MONGO_URI is undefined. Exiting.');
        process.exit(1);
    }
    await mongoose.connect(mongoURI, {
      useNewUrlParser: true,
      useUnifiedTopology: true,
    });
    console.log('🔌 Connected to ' + mongoURI.split('@')[1].split('?')[0]);

    // 1. Find the test users and their IDs
    const users = await User.find({ 
        $or: [
            { email: { $in: testEmails } },
            // Also clean up any mock names or similar emails that were generated by test scripts
            { email: { $regex: /@foodtok\.com$/i } },
            // If they are literally named 'Test' or 'experimental'
            { email: { $regex: /experimental/i } },
        ]
    });

    if (users.length === 0) {
      console.log('No test users found. Exiting.');
      // Keep going to wipe any dangling orders just in case
    } else {
        const userIds = users.map(u => u._id);
        console.log(`🧹 Found ${users.length} test users to delete.`);
        
        // Output who exactly we're deleting
        users.forEach(u => console.log(` - Deleting User/Chef: ${u.fullName} (${u.email})`));

        // 2. Wipe related entities
        const dishRes = await Dish.deleteMany({ owner: { $in: userIds } });
        console.log(` - Deleted ${dishRes.deletedCount} test Dishes.`);

        const menuRes = await Menu.deleteMany({ $or: [{ owner: { $in: userIds } }, { chef: { $in: userIds } }] });
        console.log(` - Deleted ${menuRes.deletedCount} test Menus.`);

        const sectionRes = await Section.deleteMany({ owner: { $in: userIds } });
        console.log(` - Deleted ${sectionRes.deletedCount} test Sections.`);

        const branchRes = await ChefBranch.deleteMany({ chef: { $in: userIds } });
        console.log(` - Deleted ${branchRes.deletedCount} test ChefBranches.`);

        const reelRes = await Reel.deleteMany({ chef: { $in: userIds } });
        console.log(` - Deleted ${reelRes.deletedCount} test Reels.`);

        const storyRes = await Story.deleteMany({ chef: { $in: userIds } });
        console.log(` - Deleted ${storyRes.deletedCount} test Stories.`);

        const orderRes = await Order.deleteMany({ $or: [{ chef: { $in: userIds } }, { user: { $in: userIds } }] });
        console.log(` - Deleted ${orderRes.deletedCount} test Orders tied to test users.`);

        const notifRes = await Notification.deleteMany({ $or: [{ to_user: { $in: userIds } }, { from_user: { $in: userIds } }] });
        console.log(` - Deleted ${notifRes.deletedCount} test Notifications tied to test users.`);

        // 3. Delete the actual users
        const uRes = await User.deleteMany({ _id: { $in: userIds } });
        console.log(` - Deleted ${uRes.deletedCount} test User documents.`);
    }

    // Since this is going to be a fresh production database, we also clear ALL orders, just to be safe.
    // As mentioned in the plan, flushing all orders from staging prevents fake test orders from polluting prod stats.
    console.log('\n🧹 Emptying all Orders and Notifications from staging before production use...');
    const allOrderRes = await Order.deleteMany({});
    console.log(` - Flushed ${allOrderRes.deletedCount} TOTAL remaining orders.`);
    const allNotifRes = await Notification.deleteMany({});
    console.log(` - Flushed ${allNotifRes.deletedCount} TOTAL remaining notifications.`);

    // 4. Verification Check
    console.log('\n✅ Script Complete. Remaining Users in DB:');
    const remainingUsers = await User.find({}, 'email type fullName').lean();
    console.log(`Found ${remainingUsers.length} users remaining:`);
    remainingUsers.forEach(u => {
        console.log(` • [${u.type || 'unknown'}] ${u.fullName} (${u.email})`);
    });

  } catch (err) {
    console.error('❌ Error during cleanup:', err);
  } finally {
    await mongoose.disconnect();
    process.exit(0);
  }
}

cleanupStaging();
